/// Confronta anche maiuscole, accenti e separatori diversi, senza inventare
/// una provincia quando il valore è sconosciuto.
fn normalized(value: &str) -> String {
    let mut result = String::new();
    for ch in value.trim().to_lowercase().chars() {
        match ch {
            'à' | 'á' | 'â' | 'ä' => result.push('a'),
            'è' | 'é' | 'ê' | 'ë' => result.push('e'),
            'ì' | 'í' | 'î' | 'ï' => result.push('i'),
            'ò' | 'ó' | 'ô' | 'ö' => result.push('o'),
            'ù' | 'ú' | 'û' | 'ü' => result.push('u'),
            c if c.is_alphanumeric() => result.push(c),
            _ => {},
        }
    }
    result
}

pub fn province_from_name(value: &str) -> Option<&'static str> {
    let key = normalized(value);
    if key.is_empty() { return None; }
    if let Some((code, _)) = PROVINCES.iter().find(|(code, _)| normalized(code) == key) {
        return Some(*code);
    }
    // Denominazioni frequenti nei dataset storici ANAC.
    let alias = match key.as_str() {
        "monza" | "monzaebrianza" => Some("MB"),
        "reggioemilia" => Some("RE"),
        "forlicesena" => Some("FC"),
        "massaecarrara" => Some("MS"),
        "pesarourbino" => Some("PU"),
        "bolzanobozen" => Some("BZ"),
        "aoste" => Some("AO"),
        _ => None,
    };
    alias.or_else(|| NAMES.iter().find(|(_, name)| normalized(name) == key).map(|(code, _)| *code))
}

pub fn region_for_province(code: &str) -> Option<&'static str> {
    PROVINCES.iter().find(|(candidate, _)| candidate.eq_ignore_ascii_case(code.trim()))
        .map(|(_, region)| *region)
}

pub fn regions() -> Vec<&'static str> {
    let mut values: Vec<_> = PROVINCES.iter().map(|(_, region)| *region).collect();
    values.sort_unstable();
    values.dedup();
    values
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn normalizes_codes_names_and_aliases() {
        assert_eq!(province_from_name(" mb "), Some("MB"));
        assert_eq!(province_from_name("Monza e della Brianza"), Some("MB"));
        assert_eq!(province_from_name("Forli Cesena"), Some("FC"));
        assert_eq!(province_from_name("invalido"), None);
        assert_eq!(region_for_province("na"), Some("Campania"));
        assert_eq!(regions().len(), 20);
    }
}
